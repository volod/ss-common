"""Generate proto3 messages for the Go agent and future Rust or C++ consumers, and compile them.

Types: int `int32`, long `int64`, float `float`, double `double`, timestamp
`google.protobuf.Timestamp`, date `string` (ISO 8601 date), json `google.protobuf.Struct`, array
`repeated T`. An optional scalar is `optional T`; message types and repeated fields have no
separate null state, so an optional array arrives as empty and an optional object as unset.

Compilation uses the protoc bundled with grpcio-tools and its well-known-type includes, so no
system protoc is needed. It writes a self-contained descriptor set (`--include_imports`) and the
Python bindings next to the `.proto` file.
"""

import pathlib
from importlib import resources

from ss_contracts.tooling.odcs import ContractSpec, FieldSpec

_PROTO_TYPES: dict[str, str] = {
    "string": "string",
    "bytes": "bytes",
    "int": "int32",
    "long": "int64",
    "float": "float",
    "double": "double",
    "boolean": "bool",
    "timestamp": "google.protobuf.Timestamp",
    "date": "string",
    "json": "google.protobuf.Struct",
}
_WELL_KNOWN_IMPORTS: dict[str, str] = {
    "google.protobuf.Timestamp": "google/protobuf/timestamp.proto",
    "google.protobuf.Struct": "google/protobuf/struct.proto",
}
_INDENT = "  "


class ProtoCompileError(RuntimeError):
    """protoc rejected a generated file."""


def _field_type(fld: FieldSpec) -> str:
    if fld.kind == "array":
        return f"repeated {_PROTO_TYPES[str(fld.item_kind)]}"
    proto_type = _PROTO_TYPES[fld.kind]
    if fld.required or proto_type in _WELL_KNOWN_IMPORTS:
        return proto_type
    return f"optional {proto_type}"


def _imports(spec: ContractSpec) -> list[str]:
    kinds = {str(fld.item_kind) if fld.kind == "array" else fld.kind for fld in spec.fields}
    proto_types = {_PROTO_TYPES[kind] for kind in kinds}
    paths = sorted(_WELL_KNOWN_IMPORTS[t] for t in proto_types if t in _WELL_KNOWN_IMPORTS)
    return [f'import "{path}";' for path in paths]


def _reserved(spec: ContractSpec) -> list[str]:
    hints = spec.generation_hints("proto")
    lines: list[str] = []
    numbers = sorted(hints.get("reserved") or [])
    if numbers:
        lines.append(f"{_INDENT}reserved {', '.join(str(n) for n in numbers)};")
    names = ", ".join('"' + name + '"' for name in sorted(hints.get("reservedNames") or []))
    if names:
        lines.append(f"{_INDENT}reserved {names};")
    return lines


def render(spec: ContractSpec) -> str:
    hints = spec.generation_hints("proto")
    lines = [
        f"// Contract {spec.contract_id} {spec.version}; generated by ss-contracts, do not edit.",
        'syntax = "proto3";',
        "",
        f"package {hints['package']};",
        "",
    ]
    imports = _imports(spec)
    if imports:
        lines.extend([*imports, ""])
    if hints.get("goPackage"):
        lines.extend([f'option go_package = "{hints["goPackage"]}";', ""])
    lines.append(f"// {spec.purpose}")
    lines.append(f"message {hints['messageName']} {{")
    lines.extend(_reserved(spec))
    for fld in spec.fields:
        number = fld.generation["proto"]["fieldNumber"]
        lines.append(f"{_INDENT}// {fld.description}")
        lines.append(f"{_INDENT}{_field_type(fld)} {fld.name} = {number};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def compile_proto(proto_path: pathlib.Path) -> pathlib.Path:
    """Compile one generated file with the bundled protoc; return the descriptor-set path."""
    from grpc_tools import protoc

    include = resources.files("grpc_tools").joinpath("_proto")
    out_dir = proto_path.parent
    descriptor = out_dir / f"{proto_path.stem}.pb"
    args = [
        "protoc",
        f"--proto_path={out_dir}",
        f"--proto_path={include}",
        f"--descriptor_set_out={descriptor}",
        "--include_imports",
        f"--python_out={out_dir}",
        proto_path.name,
    ]
    if protoc.main(args) != 0:
        raise ProtoCompileError(f"protoc failed for {proto_path.name}")
    return descriptor
